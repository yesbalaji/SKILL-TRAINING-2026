a = 15
b = 4

# 1. Addition (+)
print("Addition:", a + b)  # Output: 19

# 2. Subtraction (-)
print("Subtraction:", a - b)  # Output: 11

# 3. Multiplication (*)
print("Multiplication:", a * b)  # Output: 60

# 4. Division (/) - Always returns a decimal (float)
print("Division:", a / b)  # Output: 3.75

# 5. Floor Division (//) - Rounds down to the nearest whole number
print("Floor Division:", a // b)  # Output: 3

# 6. Modulus (%) - Returns the remainder of the division
print("Modulus:", a % b)  # Output: 3

# 7. Exponentiation (**) - Raises 'a' to the power of 'b'
print("Exponentiation:", a**b)  # Output: 50625
